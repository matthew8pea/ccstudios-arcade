// Builds dist/game.pack.js: every ES module + every GLB model in one classic script, so the
// game also runs when index.html is opened straight from the folder (file://), where browsers
// refuse to load ES modules and 3D models. The served game (Play.bat / server.js) does not use it.
// Usage: node tools/pack.js        (zero dependencies; Play.bat runs it automatically)
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const ENTRY = 'src/main.js';
const OUT = path.join(ROOT, 'dist', 'game.pack.js');
const MARK = 'gcd-pack:';
// keep in sync with the import map in index.html
const IMPORT_MAP = {
  'three': 'vendor/three/build/three.module.js',
  'three/addons/': 'vendor/three/examples/jsm/',
};

function resolveSpec(from, spec) {
  if (IMPORT_MAP[spec]) return IMPORT_MAP[spec];
  for (const [k, v] of Object.entries(IMPORT_MAP)) if (k.endsWith('/') && spec.startsWith(k)) return v + spec.slice(k.length);
  if (!spec.startsWith('.')) throw new Error(`Cannot resolve "${spec}" imported by ${from}`);
  return path.posix.normalize(path.posix.join(path.posix.dirname(from), spec));
}

// `import ... from '...'`, `export ... from '...'` and `import '...'` at the start of a statement
const FROM_RE = /(^|\n)(\s*(?:import|export)\b[^'"`;]*?\bfrom\s*)(['"])([^'"\n]+)\3/g;
const BARE_RE = /(^|\n)(\s*import\s*)(['"])([^'"\n]+)\3/g;

function pack() {
  const sources = {};
  const visiting = new Set();
  const visit = (rel) => {
    if (sources[rel] !== undefined) return;
    if (visiting.has(rel)) throw new Error('Import cycle through ' + rel);
    visiting.add(rel);
    let src = fs.readFileSync(path.join(ROOT, rel), 'utf8').replace(/^﻿/, '');
    const deps = [];
    const rewrite = (m, lead, kw, q, spec) => {
      const dep = resolveSpec(rel, spec);
      if (!fs.existsSync(path.join(ROOT, dep))) throw new Error(`${rel}: missing import ${spec} -> ${dep}`);
      deps.push(dep);
      return `${lead}${kw}${q}${MARK}${dep}${q}`;
    };
    src = src.replace(FROM_RE, rewrite).replace(BARE_RE, rewrite);
    for (const d of deps) visit(d);
    visiting.delete(rel);
    sources[rel] = src;
  };
  visit(ENTRY);

  const models = {};
  const dir = path.join(ROOT, 'assets', 'models');
  for (const f of fs.readdirSync(dir).filter((f) => f.endsWith('.glb')).sort()) {
    models[f.replace(/\.glb$/, '')] = fs.readFileSync(path.join(dir, f)).toString('base64');
  }

  const out = `// Generated by tools/pack.js - do not edit. Lets index.html run from file:// (no web server).
(function () {
  var SOURCES = ${JSON.stringify(sources)};
  window.__GCD_MODELS = ${JSON.stringify(models)};
  var urls = {}, busy = {};
  function load(p) {
    if (urls[p]) return urls[p];
    if (busy[p]) throw new Error('import cycle: ' + p);
    busy[p] = true;
    var code = SOURCES[p].replace(/(['"])${MARK}([^'"]+)\\1/g, function (m, q, dep) { return q + load(dep) + q; });
    return (urls[p] = URL.createObjectURL(new Blob([code], { type: 'text/javascript' })));
  }
  import(load(${JSON.stringify(ENTRY)})).catch(function (e) {
    console.error(e);
    var t = document.getElementById('loadtext');
    if (t) t.textContent = 'The game failed to start from the folder (' + e.message + '). Try Play.bat instead.';
  });
})();
`;
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, out);
  return { modules: Object.keys(sources).length, models: Object.keys(models).length, bytes: out.length };
}

if (require.main === module) {
  const r = pack();
  console.log(`Packed ${r.modules} modules + ${r.models} models into dist/game.pack.js (${(r.bytes / 1048576).toFixed(1)} MB)`);
}
module.exports = { pack };
